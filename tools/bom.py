"""Bill of materials from a solidcraft-cli build report (``--json-out``).

Cut list (extrusions grouped by profile + length), joint hardware, and a fastener / T-nut
estimate. Writes BOM.md. Rule and decision IDs refer to docs/EXTRUSION_GUIDE.md.

    python tools/bom.py build/report.json
"""

from __future__ import annotations

import logging
import sys
from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from audit import Box, load_bodies

__all__ = ["CutPiece", "cut_list", "render", "main"]

log = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "BOM.md"
STANDARDS = ("HFS5", "8020", "VSLOT")
SPARE_TNUTS_PER_MEMBER = 2  # F2: preload spares in every member you might use later

# End machining per member (D8: end anchors need tapped ends + access holes in the receiver).
MACHINING: Mapping[str, str] = {
    "Upright": "access holes for the crossbar and side-rail / speaker-arm anchors (M2)",
    "Crossbar": "both ends tapped M5 for end anchors (M1, D8)",
    "SideRail": "rear end tapped M5 (M1, D8)",
    "Stile": "both ends tapped M5 for end anchors into the crossbar slots (M1, D7)",
}
# (bolts into T-nuts, other bolts) per hardware piece. Misumi counts from the catalog
# (refs/misumi_brackets/p2259.pdf); the -SET suffix ships them with each part.
FASTENERS: Mapping[str, tuple[int, int]] = {
    "Bracket": (2, 0),         # HBLFSN5: 1 bolt per leg
    "Plate_T": (8, 0),         # HPTTD5: 8 x M5
    "Plate_L": (8, 0),         # HPTLD5: 8 x M5
    "Standoff": (1, 0),        # M5 standoff into a T-nut, + 1 screw through the panel
    "VESA": (2, 4),            # 2 per stile into T-nuts, 4 M4 into the monitor
    "SpkMount": (2, 1),        # flange: 2 into the upright front slot; swivel: speaker's own screw
}


@dataclass(frozen=True)
class CutPiece:
    member: str
    std: str
    profile: str
    length_mm: float


def _split(name: str) -> tuple[str, str] | None:
    for std in STANDARDS:
        if name.endswith(f"_{std}"):
            return name.removesuffix(f"_{std}"), std
    return None


def cut_list(bodies: Mapping[str, Box]) -> list[CutPiece]:
    pieces: list[CutPiece] = []
    for name, box in bodies.items():
        split = _split(name)
        if split is None:
            continue
        dims = sorted(box.size)
        profile = "4040" if dims[0] > 30 else "2040"
        pieces.append(CutPiece(split[0], split[1], profile, round(dims[2] * 2) / 2))
    return pieces


def _hardware(bodies: Mapping[str, Box]) -> Counter[str]:
    hw: Counter[str] = Counter()
    for name in bodies:
        if name.startswith("Bracket_"):
            hw["Bracket"] += 1
        elif name.startswith("Plate_SideRail"):
            hw["Plate_T"] += 1
        elif name.startswith("Plate_"):
            hw["Plate_L"] += 1
        elif name.startswith("Standoff_"):
            hw["Standoff"] += 1
        elif name.startswith("SpkMount_") and name.endswith("_Flange"):
            hw["SpkMount"] += 1
        elif name in ("Monitor_Main", "Monitor_Side"):
            hw["VESA"] += 1
    return hw


HW_LABEL: Mapping[str, str] = {
    "Bracket": "Misumi HBLFSN5-SET gusset bracket, 1-slot, 30 mm legs (rail/bar ends + stiles)",
    "Plate_T": "Misumi HPTTD5-SET T plate, 110 x 80 x 2.3 mm (side rail to upright, outer face)",
    "Plate_L": "Misumi HPTLD5-SET L plate, 80 x 80 x 2.3 mm (crossbar to upright, back face)",
    "Standoff": "M5 standoff, 10 mm dia x 12 mm (panel)",
    "VESA": "VESA adapter, 3D printed (wedge for tilt / toe-in)",
    "SpkMount": "Speaker bracket: flange in the upright front slot + block out to the speaker's swivel mount",
}


def render(pieces: Sequence[CutPiece], hw: Mapping[str, int]) -> str:
    std = pieces[0].std if pieces else "?"
    lines = ["# Bill of materials", "",
             f"Generated by `tools/bom.py` from the model (standard: **{std}**). Do not hand-edit; rebuild.",
             "Bounding-box based: check lengths against the model before ordering.", "",
             "## Extrusion cut list", "",
             "| Qty | Profile | Length (mm) | Members | End machining |", "|---|---|---|---|---|"]
    groups: Counter[tuple[str, float, str]] = Counter(
        (p.profile, p.length_mm, p.member.split("_")[0]) for p in pieces)
    members: dict[tuple[str, float, str], list[str]] = {}
    for p in pieces:
        members.setdefault((p.profile, p.length_mm, p.member.split("_")[0]), []).append(p.member)
    for key in sorted(groups):
        profile, length, kind = key
        lines.append(f"| {groups[key]} | {std}-{profile} | {length:g} | {', '.join(sorted(members[key]))} "
                     f"| {MACHINING.get(kind, '')} |")
    totals: Counter[str] = Counter()
    for p in pieces:
        totals[p.profile] += p.length_mm
    lines += ["", "Total: " + ", ".join(f"{std}-{k} {v / 1000:.2f} m" for k, v in sorted(totals.items())), "",
              "## Joint hardware", "", "| Qty | Item |", "|---|---|"]
    lines += [f"| {n} | {HW_LABEL[k]} |" for k, n in sorted(hw.items())]
    slot_bolts = sum(FASTENERS[k][0] * n for k, n in hw.items())
    other = sum(FASTENERS[k][1] * n for k, n in hw.items())
    anchors = sum(1 for p in pieces if p.member.startswith(("Crossbar", "Stile"))) * 2 + sum(
        1 for p in pieces if p.member.startswith("SideRail"))
    spares = SPARE_TNUTS_PER_MEMBER * len(pieces)
    lines += ["", "## Fasteners (estimate)", "", "| Qty | Item |", "|---|---|",
              f"| {slot_bolts} | M5 bolt + T-nut pairs into slots (resin-coated / locking nuts, F4; 6.8 N*m, F3) |",
              f"| {spares} | spare pre-assembly T-nuts, {SPARE_TNUTS_PER_MEMBER} per member (F2) |",
              f"| {anchors} | end anchors / end-tap screws (D8) |",
              f"| {other} | other screws (VESA M4, speaker swivel, panel) |",
              "| TBD | side rail to top support bolts (D9, after hole measurements) |", ""]
    return "\n".join(lines)


def main(argv: Sequence[str]) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if len(argv) != 2:
        log.error(__doc__)
        return 2
    bodies = load_bodies(Path(argv[1]))
    OUT.write_text(render(cut_list(bodies), _hardware(bodies)), encoding="utf-8")
    log.info("wrote %s", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
